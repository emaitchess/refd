// '+' cells render in both checkerboard phases: phase A visible at rest,
// phase B hidden. On ancestor hover the phases flip in hard steps (see
// global.css) so the dither "crawls" while solid pixels hold the shape.
export const DitherIcon = ({
  name,
  size = 16,
  className,
}: {
  name: DitherIconName;
  size?: number;
  className?: string;
}) => {
  const rows = GLYPHS[name];
  const gw = rows[0]?.length ?? 12;
  return (
    // biome-ignore lint/a11y/noSvgWithoutTitle: decorative glyph, rendered aria-hidden
    <svg
      viewBox={`0 0 ${gw} ${rows.length}`}
      width={size}
      height={size}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden
      className={cn('dither-icon', className)}
    >
      {rows.flatMap((row, y) =>
        [...row].map((cell, x) => {
          if (cell === '#') {
            return <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />;
          }
          if (cell === '+') {
            const phase = (x + y) % 2 === 0 ? 'dp-a' : 'dp-b';
            return (
              <rect
                key={`${x}-${y}`}
                className={phase}
                x={x}
                y={y}
                width={1}
                height={1}
              />
            );
          }
          return null;
        }),
      )}
    </svg>
  );
};
